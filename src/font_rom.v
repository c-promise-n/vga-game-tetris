`timescale 1ns / 1ps
module font_rom(
    input  wire [5:0] char_code,        // 0-36
    input  wire [2:0] glyph_row,       // 0-7
    output wire [7:0] row_bits       // bit7 = leftmost pixel of that row
);

    reg [63:0] glyph;

    always @(*) begin
        case (char_code)
        6'd 0: glyph = 64'h0000000000000000;  // ' '
        6'd 1: glyph = 64'h004444447C444438;  // 'A'
        6'd 2: glyph = 64'h0078444478444478;  // 'B'
        6'd 3: glyph = 64'h0038444040404438;  // 'C'
        6'd 4: glyph = 64'h0078444444444478;  // 'D'
        6'd 5: glyph = 64'h007C40407840407C;  // 'E'
        6'd 6: glyph = 64'h004040407840407C;  // 'F'
        6'd 7: glyph = 64'h003844445C404438;  // 'G'
        6'd 8: glyph = 64'h004444447C444444;  // 'H'
        6'd 9: glyph = 64'h0038101010101038;  // 'I'
        6'd10: glyph = 64'h003048480808081C;  // 'J'
        6'd11: glyph = 64'h0044485060504844;  // 'K'
        6'd12: glyph = 64'h007C404040404040;  // 'L'
        6'd13: glyph = 64'h0044444444546C44;  // 'M'
        6'd14: glyph = 64'h004444444C546444;  // 'N'
        6'd15: glyph = 64'h0038444444444438;  // 'O'
        6'd16: glyph = 64'h0040404078444478;  // 'P'
        6'd17: glyph = 64'h0034485444444438;  // 'Q'
        6'd18: glyph = 64'h0044485078444478;  // 'R'
        6'd19: glyph = 64'h007804043840403C;  // 'S'
        6'd20: glyph = 64'h001010101010107C;  // 'T'
        6'd21: glyph = 64'h0038444444444444;  // 'U'
        6'd22: glyph = 64'h0010284444444444;  // 'V'
        6'd23: glyph = 64'h00446C5444444444;  // 'W'
        6'd24: glyph = 64'h0044442810284444;  // 'X'
        6'd25: glyph = 64'h0010101010284444;  // 'Y'
        6'd26: glyph = 64'h007C40201008047C;  // 'Z'
        6'd27: glyph = 64'h00384464544C4438;  // '0'
        6'd28: glyph = 64'h0038101010103010;  // '1'
        6'd29: glyph = 64'h007C201008044438;  // '2'
        6'd30: glyph = 64'h0038440418044438;  // '3'
        6'd31: glyph = 64'h0008087C48281808;  // '4'
        6'd32: glyph = 64'h003844040478407C;  // '5'
        6'd33: glyph = 64'h0038444478402018;  // '6'
        6'd34: glyph = 64'h002020201008047C;  // '7'
        6'd35: glyph = 64'h0038444438444438;  // '8'
        6'd36: glyph = 64'h003008043C444438;  // '9'
            default: glyph = 64'h0000000000000000;
        endcase
    end

    assign row_bits = glyph[{glyph_row, 3'b000} +: 8];

endmodule
